import { NextResponse } from "next/server";
import { resolveSessionPath } from "@/lib/session-reader";
import { startRpcSession, getRpcSession } from "@/lib/rpc-manager";
import { engineForSession } from "@/lib/engine";

// POST /api/agent/[id] - Send a command to an existing session
export async function POST(
  req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;

  try {
    const { engine, ...body } = await req.json() as { type: string; engine?: unknown; [key: string]: unknown };
    if (engine !== undefined && engine !== engineForSession(id)) {
      return NextResponse.json({ error: "An existing session cannot change engines. Start a new session instead." }, { status: 409 });
    }

    // Fast path: already-running session
    const existing = getRpcSession(id);
    if (existing?.isAlive()) {
      const result = await existing.send(body);
      return NextResponse.json({ success: true, data: result });
    }

    // A stale queue action must not start a new agent or pretend it cancelled
    // work that belonged to a previous process.
    if (body.type === "recall_queued_message" && typeof body.id === "string" && body.id.startsWith("web-follow-up:")) {
      return NextResponse.json({ success: true, data: { removed: false, uncertain: true } });
    }
    const filePath = await resolveSessionPath(id);
    if (!filePath) {
      return NextResponse.json({ error: "Session not found" }, { status: 404 });
    }
    const { session } = await startRpcSession(id, filePath, undefined);
    const result = await session.send(body);

    return NextResponse.json({ success: true, data: result });
  } catch (error) {
    return NextResponse.json({ error: String(error) }, { status: 500 });
  }
}

// GET /api/agent/[id] - Get current agent state
export async function GET(
  _req: Request,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;

  try {
    const session = getRpcSession(id);
    if (!session || !session.isAlive()) {
      return NextResponse.json({ running: false });
    }

    const state = await session.send({ type: "get_state" });
    return NextResponse.json({ running: true, state });
  } catch (error) {
    return NextResponse.json({ error: String(error) }, { status: 500 });
  }
}
