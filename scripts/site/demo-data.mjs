function usage(input, output, cacheRead = 0) {
  return { input, output, cacheRead, cacheWrite: 0, totalTokens: input + output + cacheRead, cost: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 } };
}

/**
 * turns: [{ user, steps: [{ text?, thinking?, tools?: [{ name, args, result, details?, isError? }] }] }]
 * Each step becomes one assistant message; tool results follow it.
 */
function session(engine, cwd, title, endAgo, turns) {
  const id = randomUUID();
  const flat = engine === "claude" || engine === "codex";
  const dir = join(STORES[engine], "sessions", flat ? "" : `--${cwd.slice(1).replaceAll("/", "-")}--`);
  const start = NOW - endAgo - turns.length * 6 * min;
  const stamp = new Date(start).toISOString().replace(/[:.]/g, "-");
  const path = join(dir, flat ? `${id}.jsonl` : `${stamp}_${id}.jsonl`);
  const header = { type: "session", version: 3, id, timestamp: new Date(start).toISOString(), cwd, ...(flat ? { projection: engine === "claude" ? "claude-code" : "codex-cli" } : {}) };
  const lines = [header];
  let parent = null, t = start;
  const push = (record) => {
    const entryId = randomUUID().slice(0, 8);
    lines.push({ ...record, id: entryId, parentId: parent, timestamp: new Date(t).toISOString() });
    parent = entryId;
  };
  const m = MODELS[engine];
  push({ type: "model_change", provider: m.provider, modelId: m.model });
  push({ type: "session_info", name: title });
  for (const turn of turns) {
    t += 20_000;
    push({ type: "message", message: { role: "user", content: [{ type: "text", text: turn.user }], timestamp: t } });
    turn.steps.forEach((step, index) => {
      t += 9_000;
      const content = [];
      if (step.thinking) content.push({ type: "thinking", thinking: step.thinking });
      if (step.text) content.push({ type: "text", text: step.text });
      const calls = (step.tools ?? []).map((tool) => ({ ...tool, id: `call_${randomUUID().slice(0, 12)}` }));
      for (const call of calls) content.push({ type: "toolCall", id: call.id, name: call.name, arguments: call.args });
      const last = index === turn.steps.length - 1;
      push({ type: "message", message: { role: "assistant", content, ...m, usage: usage(4200 + index * 900, 380 + index * 140, 18_000), stopReason: calls.length ? "toolUse" : "stop", timestamp: t } });
      for (const call of calls) {
        t += 3_000;
        push({ type: "message", message: { role: "toolResult", toolCallId: call.id, toolName: call.name, content: [{ type: "text", text: call.result }], ...(call.details ? { details: call.details } : {}), isError: Boolean(call.isError), timestamp: t } });
      }
      if (last) t += 4_000;
    });
  }
  write(path, lines.map((line) => JSON.stringify(line)).join("\n") + "\n");
  const end = new Date(NOW - endAgo);
  utimesSync(path, end, end);
}

