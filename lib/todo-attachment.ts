import { sortTodosForDisplay, type TodoItem } from "./todo-types";

/**
 * Agent-readable copies of the web todo list. Open items carry the same
 * numbers as the web card, so "todo item 2" means one thing everywhere. The
 * list is read-only for agents: the web card owns every change.
 */

const OPEN_TAG = "<todo-list>";
const CLOSE_TAG = "</todo-list>";
/** Only a block that ends the message counts; earlier text is the user's own. */
const TRAILING_BLOCK_RE = /^<todo-list>\n([\s\S]*)\n<\/todo-list>\s*$/;
const DONE_LIMIT = 20;

/**
 * The message refers to the todo list: 待办/待辦, "todo list", "todo #2",
 * "todo item", or "todo" right before Chinese text ("todo里第二项"). A bare
 * English "TODO" (code comments) does not.
 */
const MENTION_RE = /待办|待辦|\bto-?do\s*-?\s*lists?\b|\bto-?dos?\s*#\s*\d+|\bto-?dos?\s+items?\b|\bto-?dos?(?=\s*[\u3400-\u9fff])/i;

export function mentionsTodoList(text: string): boolean {
  return MENTION_RE.test(text);
}

function oneLine(text: string): string {
  // Keep item text from closing the block early.
  return text.replace(/\s+/g, " ").trim().replace(/<\/todo-list/gi, "<\\/todo-list");
}

function sourceNote(item: TodoItem): string | null {
  const source = item.source;
  if (!source) return null;
  const title = source.sessionTitle ? `"${oneLine(source.sessionTitle)}"` : "untitled";
  const what = source.role === "user" ? ", a user message" : source.role === "assistant" ? ", an agent reply" : "";
  return `from conversation ${title} (session ${source.sessionId}${source.entryId ? `, entry ${source.entryId}` : ""}${what})`;
}

/** Plain-text list shared by the message attachment and the Markdown file. */
export function formatTodoLines(items: TodoItem[], options: { doneLimit?: number } = {}): string[] {
  const { open, done } = sortTodosForDisplay(items);
  const lines = ["Open (numbered as in the web todo card):"];
  if (!open.length) lines.push("(none)");
  open.forEach((item, index) => {
    lines.push(`${index + 1}. ${oneLine(item.text)}`);
    const note = sourceNote(item);
    if (note) lines.push(`   ${note}`);
  });
  const limit = options.doneLimit ?? DONE_LIMIT;
  if (done.length && limit > 0) {
    lines.push(done.length > limit ? `Done (latest ${limit} of ${done.length}):` : "Done:");
    for (const item of done.slice(0, limit)) lines.push(`- ${oneLine(item.text)}`);
  }
  return lines;
}

/** Appended to a prompt that mentions the todo list. */
export function appendTodoList(text: string, items: TodoItem[]): string {
  const body = [
    "The user's todo list from OMP Web, attached because the message refers to it. It is read-only here; the user checks items off in the web card.",
    ...formatTodoLines(items),
  ].join("\n");
  return `${text}\n\n${OPEN_TAG}\n${body}\n${CLOSE_TAG}`;
}

/** Separate a trailing attached list from the text the user typed. */
export function splitTodoListBlock(text: string): { text: string; todo: string | null } {
  // Items are single lines, so the block's own opening tag is the last one.
  const at = text.lastIndexOf(`${OPEN_TAG}\n`);
  if (at < 0) return { text, todo: null };
  const match = TRAILING_BLOCK_RE.exec(text.slice(at));
  if (!match) return { text, todo: null };
  return { text: text.slice(0, at).trimEnd(), todo: match[1] };
}

/** Markdown copy kept beside `todos.json` for agents that read files. */
export function todoMarkdown(items: TodoItem[], updatedAt: number): string {
  return [
    "# Todo list (OMP Web)",
    "",
    "<!-- Generated by omp-web from todos.json on every change; edits here are overwritten. -->",
    `Updated: ${new Date(updatedAt).toISOString()}`,
    "Read-only for agents: the user adds, edits and checks off items in the web todo card.",
    "",
    ...formatTodoLines(items, { doneLimit: 50 }),
    "",
  ].join("\n");
}
